mod support;

use std::path::PathBuf;
use support::{Engine, Runner};

const START: &str = "<!-- command-reference:start (generated by `elise commands --markdown`; run the readme test with ELISE_UPDATE_README=1 to rewrite) -->";
const END: &str = "<!-- command-reference:end -->";

fn readme_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("README.md")
}

#[test]
fn the_readme_command_reference_is_what_the_cli_generates() {
    let mut runner = Runner::new(&Engine::start());
    runner.url = Engine::unreachable_url();
    let generated = runner.run(&["commands", "--markdown"], "");
    assert_eq!(generated.code, 0, "{}", generated.stderr);
    let readme = std::fs::read_to_string(readme_path()).unwrap().replace("\r\n", "\n");
    let start = readme.find(START).expect("README.md has the command-reference start marker");
    let end = readme.find(END).expect("README.md has the command-reference end marker");
    let current = &readme[start + START.len()..end];
    let wanted = format!("\n{}", generated.stdout);

    if std::env::var_os("ELISE_UPDATE_README").is_some() {
        let updated = format!("{}{}{}", &readme[..start + START.len()], wanted, &readme[end..]);
        std::fs::write(readme_path(), updated).unwrap();
        return;
    }

    assert_eq!(
        current, wanted,
        "the README command reference is stale: run `ELISE_UPDATE_README=1 cargo test -p elise-runner-cli --test readme` in apps/elise-runner-cli"
    );
}
